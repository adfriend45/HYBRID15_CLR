!======================================================================!
program HYBRID15_CLR
!----------------------------------------------------------------------!
use PARS_MOD
use VARS_MOD
!----------------------------------------------------------------------!
implicit none
!----------------------------------------------------------------------!
write (*,*) 'HYBRID15_CLR running'
!----------------------------------------------------------------------!
open (10, file = 'home_dir.txt', status = 'old')
read (10,*) home_dir
close (10)
!----------------------------------------------------------------------!
open (20, file = trim(home_dir)//'/CLR/HYBRID15_CLR/results/&
     &HYBRID15_CLR_dt_output.txt', status = 'unknown')
!----------------------------------------------------------------------!
call read_HYBRID15_CLR_forcing
!----------------------------------------------------------------------!
write (*,*)
write (*,'(a94)') ' kyr kyr_ce    GPP_ann     PPT_ann      RO_ann &
            &     ET_ann     NEE_ann     biomass         SOM'
write (*,'(a94)') '    n   CE  g[C] m-2 yr-1  mm yr-1     mm yr-1 &
            &    mm yr-1 g[C] m-2 yr-1 g[DM] m-2   g[DM] m-2'
!----------------------------------------------------------------------!
sm = 1500.0
LAI = 4.0
biomass = 200.0
SOM = 40000.0
!----------------------------------------------------------------------!
kyr_ce = 2000
!----------------------------------------------------------------------!
do kyr = 1, 2
  kyr_ce = kyr_ce + 1
  ca_fmol = co2_ppm (kyr_ce) / 1.0e6 ! mol[CO2] mol[air]-1
  GPP_ann = zero
  PPT_ann = zero
  RO_ann  = zero
  ET_ann  = zero
  NEE_ann = zero
  it = 0
  do kday = 1, ndays
    hr = 0.0 - dt_hr
    do kt = 1, nt
      !----------------------------------------------------------------!
      if (mod (kt-1,12) == 0) it = it + 1
      !----------------------------------------------------------------!
      hr = hr + dt_hr
      !----------------------------------------------------------------!
      write (20,'(4i5,4f12.4)') kyr, kyr_ce, kday, kt, hr, &
                                co2_ppm (kyr_ce), tswrf, sm
      !----------------------------------------------------------------!
      ! Local air temperature                                       (oC)
      !----------------------------------------------------------------!
      TC = tmp_global (kw,it) - tf
      !----------------------------------------------------------------!
      ! Local precipitation                                     (mm s-1)
      !----------------------------------------------------------------!
      pre = pre_global (kw,it)
      !----------------------------------------------------------------!
      ! Local downwelling shortwave radiation                    (W m-2)
      !----------------------------------------------------------------!
      tswrf = tswrf_global (kw,it)
      !----------------------------------------------------------------!
      ! Local downwelling longwave radiation                     (W m-2)
      !----------------------------------------------------------------!
      dlwrf = dlwrf_global (kw,it)
      !----------------------------------------------------------------!
      ! Local specific humidity                    (kg[water] kg[air]-1)
      !----------------------------------------------------------------!
      spfh = spfh_global (kw,it)
      !----------------------------------------------------------------!
      ! Local surface pressure                                      (Pa)
      !----------------------------------------------------------------!
      pres = pres_global (kw,it)
      !----------------------------------------------------------------!
      ! Local zonal wind vector                                  (m s-1)
      !----------------------------------------------------------------!
      ugrd = ugrd_global (kw,it)
      !----------------------------------------------------------------!
      ! Local meridional wind vector                             (m s-1)
      !----------------------------------------------------------------!
      vgrd = vgrd_global (kw,it)
      !----------------------------------------------------------------!
      ! Compute crown photosynthesis, respiration, and conductance.
      !----------------------------------------------------------------!
      call crown
      !----------------------------------------------------------------!
      ! Advance soil hydrology.
      !----------------------------------------------------------------!
      call hydro
      !----------------------------------------------------------------!
      ! Advance biomass.
      !----------------------------------------------------------------!
      call grow
      !----------------------------------------------------------------!
      ! Advance SOM.
      !----------------------------------------------------------------!
      call decomp
      !----------------------------------------------------------------!
      ! Accumulate annual diagnostics.
      !----------------------------------------------------------------!
      GPP_ann = GPP_ann + dt_s * gpp
      NEE_ann = NEE_ann + dt_s * (Raut + loss - gpp)
      !----------------------------------------------------------------!
    end do ! kt
  end do ! kday
  write (*,'(2i5,7f12.4)') kyr, kyr_ce, GPP_ann, PPT_ann, RO_ann, &
                           ET_ann, NEE_ann, biomass, SOM
end do ! kyr
!----------------------------------------------------------------------!
close (20)
write (*,*)
write (*,*) 'HYBRID15_CLR finished'
!----------------------------------------------------------------------!
end program HYBRID15_CLR
!======================================================================!
